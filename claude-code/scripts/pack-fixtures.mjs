#!/usr/bin/env node
// Packs agent-file-board example boards into claude-code/tests/fixtures.ts.
//
// Mod tests cannot reach the real filesystem (`$.fs` is answered by the test's
// own hooks), so the fixture boards are embedded as data. SPEC-001 AC1.
//
// Usage: node scripts/pack-fixtures.mjs <agent-file-board-repo> [--check]
//   --check  exit 1 when tests/fixtures.ts differs from what would be written.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const EXAMPLES = { subthreads: 'examples/subthreads', fullConversation: 'examples/full-conversation' }
const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'tests', 'fixtures.ts')

const [repo, flag] = process.argv.slice(2)
if (!repo || !existsSync(join(repo, 'boardctl.py'))) {
  console.error('pack-fixtures: pass the agent-file-board repository root')
  process.exit(2)
}

function scopeFiles(root) {
  const files = []
  for (const kind of ['rooms', 'direct']) {
    const base = join(root, kind)
    if (!existsSync(base)) continue
    for (const scope of readdirSync(base).sort()) {
      if (!statSync(join(base, scope)).isDirectory()) continue
      for (const name of readdirSync(join(base, scope)).sort()) {
        if (!name.endsWith('.txt')) continue
        files.push({ dir: `${kind}/${scope}`, name, text: readFileSync(join(base, scope, name), 'utf8') })
      }
    }
  }
  return files
}

const read = path => (existsSync(path) ? readFileSync(path, 'utf8') : null)
const data = {}
for (const [key, rel] of Object.entries(EXAMPLES)) {
  const root = join(repo, rel)
  data[key] = { files: scopeFiles(root), participants: read(join(root, 'participants.json')), config: read(join(root, 'config.json')) }
}

const text = `// Generated by scripts/pack-fixtures.mjs from agent-file-board ${Object.values(EXAMPLES).join(', ')}.
// Do not edit by hand; regenerate and commit.
import type { MessageFile } from '../core/board'

export type FixtureBoard = { files: MessageFile[]; participants: string | null; config: string | null }

export const FIXTURES: Record<${Object.keys(EXAMPLES).map(k => `'${k}'`).join(' | ')}, FixtureBoard> = ${JSON.stringify(data, null, 2)}
`

if (flag === '--check') {
  const current = read(out)
  if (current !== text) {
    console.error('pack-fixtures: tests/fixtures.ts is stale; run node scripts/pack-fixtures.mjs <repo>')
    process.exit(1)
  }
  console.log('pack-fixtures: fixtures current')
} else {
  writeFileSync(out, text)
  console.log(`pack-fixtures: wrote ${out}`)
}
